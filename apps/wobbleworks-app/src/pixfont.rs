/// Shown for characters the font doesn't have: a hollow box.
const MISSING: Glyph = &["####", "#..#", "#..#", "#..#", "#..#", "#..#", "####"];

fn glyph_or_box(c: char) -> Glyph {
    glyph(c).unwrap_or(MISSING)
}

fn width_of(g: Glyph) -> f32 {
    g.iter().map(|r| r.len()).max().unwrap_or(0) as f32
}

/// Width and cap height of `text` at `scale` (descenders hang 2 × `scale` below).
pub fn size(text: &str, scale: f32) -> Vec2 {
    let cols: f32 = text.chars().map(|c| width_of(glyph_or_box(c)) + GAP).sum::<f32>();
    vec2((cols - GAP).max(0.0) * scale, CAP * scale)
}

/// The longest prefix of `text` (with "…" when cut) that fits in `max_width`.
pub fn fit(text: &str, scale: f32, max_width: f32) -> String {
    if size(text, scale).x <= max_width {
        return text.to_string();
    }
    let ell = size("…", scale).x + GAP * scale;
    let mut w = 0.0;
    let mut out = String::new();
    for c in text.chars() {
        let cw = (width_of(glyph_or_box(c)) + GAP) * scale;
        if w + cw + ell > max_width {
            break;
        }
        w += cw;
        out.push(c);
    }
    out.push('…');
    out
}

/// Paint `text` with its top-left at `pos`. `wiggle(i)` lifts letter `i` by that many font pixels
/// (for boiling titles); pass `|_| 0.0` for still text.
pub fn paint(painter: &Painter, pos: Pos2, text: &str, scale: f32, color: Color32, wiggle: impl Fn(usize) -> f32) -> Rect {
    let mut x = pos.x;
    for (i, c) in text.chars().enumerate() {
        let g = glyph_or_box(c);
        let y0 = pos.y + (wiggle(i) * scale).round();
        for (row, line) in g.iter().enumerate() {
            let y = y0 + row as f32 * scale;
            // One rectangle per run of ink, not per pixel.
            let mut run: Option<usize> = None;
            for (col, ch) in line.chars().chain(std::iter::once('.')).enumerate() {
                match (ch == '#', run) {
                    (true, None) => run = Some(col),
                    (false, Some(start)) => {
                        let r = Rect::from_min_size(pos2(x + start as f32 * scale, y), vec2((col - start) as f32 * scale, scale));
                        painter.rect_filled(r, 0.0, color);
                        run = None;
                    }
                    _ => {}
                }
            }
        }
        x += (width_of(g) + GAP) * scale;
    }
    Rect::from_min_size(pos, size(text, scale))
}

/// Paint `text` centred on `center` (cap height centred), with a hard shadow when `shadow` is set.
pub fn paint_centered(painter: &Painter, center: Pos2, text: &str, scale: f32, color: Color32, shadow: Option<Color32>) {
    let s = size(text, scale);
    let pos = pos2((center.x - s.x / 2.0).round(), (center.y - s.y / 2.0).round());
    if let Some(sh) = shadow {
        paint(painter, pos + vec2(scale, scale), text, scale, sh, |_| 0.0);
    }
    paint(painter, pos, text, scale, color, |_| 0.0);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_ascii_char_has_a_glyph_of_sane_shape() {
        for c in (32u8..127).map(char::from) {
            let g = glyph(c).unwrap_or_else(|| panic!("no glyph for {c:?}"));
            assert!(!g.is_empty() && g.len() <= ROWS as usize, "{c:?}: {} rows", g.len());
            let w = g[0].len();
            assert!(g.iter().all(|r| r.len() == w && r.chars().all(|ch| ch == '#' || ch == '.')), "{c:?}: ragged or bad chars");
            assert!(w <= 5, "{c:?} is {w} wide");
        }
    }

    #[test]
    fn measuring_and_fitting() {
        assert_eq!(size("", 2.0), vec2(0.0, 14.0));
        assert_eq!(size("A", 2.0).x, 10.0);
        assert_eq!(size("AA", 1.0).x, 11.0);
        assert_eq!(fit("short", 2.0, 1000.0), "short");
        let cut = fit("a very long status message indeed", 2.0, 80.0);
        assert!(cut.ends_with('…') && size(&cut, 2.0).x <= 80.0, "{cut}");
        assert_eq!(fit("anything", 2.0, 0.0), "…");
        // Unknown characters measure as a box rather than vanishing.
        assert!(size("猫", 1.0).x > 0.0);
    }
}
