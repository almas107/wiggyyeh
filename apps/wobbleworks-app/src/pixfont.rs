//! WobbleWorks' chunky pixel font, drawn in code (no font file): 5 × 7 capitals and digits,
//! lowercase with 2-row descenders, and ASCII punctuation. Each font pixel is painted as a square
//! `scale` points wide, so text stays crisp and blocky at any size. An original design for
//! WobbleWorks (see `ATTRIBUTION.md`).

use egui::{Color32, Painter, Pos2, Rect, Vec2, pos2, vec2};

/// Rows from the top of the cap height down; rows 7 and 8 are descenders. `#` is ink.
type Glyph = &'static [&'static str];

/// Rows above the baseline.
pub const CAP: f32 = 7.0;
/// All rows, descenders included.
pub const ROWS: f32 = 9.0;
/// Blank columns between letters.
const GAP: f32 = 1.0;

